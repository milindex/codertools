const reverseEntities = (() => {
  const map = new Map<string, string>();
  for (const [name, character] of Object.entries(NAMED_ENTITIES)) {
    if (!map.has(character)) {
      map.set(character, name);
    }
  }
  return map;
})();

const SPECIAL_CHARACTERS = new Set(['&', '<', '>', '"', "'"]);

export type EncodeEntityOptions = {
  format: EntityFormat;
  encodeNonAscii: boolean;
  encodeQuotes: boolean;
};

export const encodeHtmlEntities = (
  text: string,
  options: EncodeEntityOptions
): string => {
  let output = '';

  for (const character of text) {
    const code = character.codePointAt(0) ?? 0;
    const isSpecial = SPECIAL_CHARACTERS.has(character);
    const isQuote = character === '"' || character === "'";
    const needsEncoding =
      (isSpecial && (!isQuote || options.encodeQuotes)) ||
      (options.encodeNonAscii && code > 0x7f);

    if (!needsEncoding) {
      output += character;
      continue;
    }

    const name = reverseEntities.get(character);
    if (options.format === 'named' && name) {
      output += `&${name};`;
    } else if (options.format === 'hex') {
      output += `&#x${code.toString(16)};`;
    } else {
      output += `&#${code};`;
    }
  }

  return output;
};

export const decodeHtmlEntities = (text: string): string => {
  if (typeof document === 'undefined') {
    return text
      .replace(/&#x([0-9a-f]+);?/gi, (_match, hex: string) => {
        const code = Number.parseInt(hex, 16);
        return Number.isFinite(code) ? String.fromCodePoint(code) : _match;
      })
      .replace(/&#(\d+);?/g, (_match, decimal: string) => {
        const code = Number.parseInt(decimal, 10);
        return Number.isFinite(code) ? String.fromCodePoint(code) : _match;
      })
      .replace(/&([a-zA-Z][a-zA-Z0-9]+);/g, (match, name: string) => {
        return NAMED_ENTITIES[name] ?? match;
      });
  }

  const textarea = document.createElement('textarea');
  textarea.innerHTML = text;
  return textarea.value;
};

export const countEntities = (text: string): number =>
  (text.match(/&(?:#x?[0-9a-fA-F]+|[a-zA-Z][a-zA-Z0-9]+);/g) ?? []).length;

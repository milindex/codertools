'use client';

import { useMemo, useState } from 'react';

import { Badge } from '@/components/ui/Badge';
import { Field } from '@/components/ui/Field';
import { Panel } from '@/components/ui/Panel';
import { ResultPanel } from '@/components/ui/ResultPanel';
import { Select } from '@/components/ui/Select';
import { ToolLayout } from '@/components/ui/ToolLayout';

import { Toggle } from './_shared';

type WwwMode = 'none' | 'add' | 'remove';

export default function HtaccessGeneratorTool() {
  const [https, setHttps] = useState(true);
  const [wwwMode, setWwwMode] = useState<WwwMode>('none');
  const [spa, setSpa] = useState(true);
  const [caching, setCaching] = useState(true);
  const [compression, setCompression] = useState(true);
  const [security, setSecurity] = useState(true);

  const output = useMemo(() => {
    const blocks: string[] = [
      '# Generated by CoderTools',
      '# Apache 2.4 .htaccess rules',
    ];

    const rewriteRules: string[] = [];

    if (https && wwwMode === 'add') {
      rewriteRules.push(
        '  # Force HTTPS and add www',
        '  RewriteCond %{HTTPS} off [OR]',
        '  RewriteCond %{HTTP_HOST} !^www\\. [NC]',
        '  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]',
        '  RewriteRule ^ https://www.%1%{REQUEST_URI} [L,R=301]'
      );
    } else if (https && wwwMode === 'remove') {
      rewriteRules.push(
        '  # Force HTTPS and remove www',
        '  RewriteCond %{HTTPS} off [OR]',
        '  RewriteCond %{HTTP_HOST} ^www\\. [NC]',
        '  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]',
        '  RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]'
      );
    } else if (https) {
      rewriteRules.push(
        '  # Force HTTPS',
        '  RewriteCond %{HTTPS} off',
        '  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]'
      );
    } else if (wwwMode === 'add') {
      rewriteRules.push(
        '  # Add www',
        '  RewriteCond %{HTTP_HOST} !^www\\. [NC]',
        '  RewriteCond %{HTTP_HOST} ^(.+)$ [NC]',
        '  RewriteRule ^ %{REQUEST_SCHEME}://www.%1%{REQUEST_URI} [L,R=301]'
      );
    } else if (wwwMode === 'remove') {
      rewriteRules.push(
        '  # Remove www',
        '  RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]',
        '  RewriteRule ^ %{REQUEST_SCHEME}://%1%{REQUEST_URI} [L,R=301]'
      );
    }

    if (spa) {
      if (rewriteRules.length > 0) {
        rewriteRules.push('');
      }
      rewriteRules.push(
        '  # Single-page app fallback',
        '  RewriteCond %{REQUEST_FILENAME} !-f',
        '  RewriteCond %{REQUEST_FILENAME} !-d',
        '  RewriteRule ^ index.html [L]'
      );
    }

    if (rewriteRules.length > 0) {
      blocks.push('');
      if (spa) {
        blocks.push('Options -MultiViews');
        blocks.push('');
      }
      blocks.push('<IfModule mod_rewrite.c>', '  RewriteEngine On', '');
      blocks.push(...rewriteRules, '</IfModule>');
    }

    if (compression) {
      blocks.push(
        '',
        '<IfModule mod_deflate.c>',
        '  AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml',
        '  AddOutputFilterByType DEFLATE application/javascript application/json application/xml',
        '  AddOutputFilterByType DEFLATE image/svg+xml font/woff2',
        '</IfModule>'
      );
    }

    if (caching) {
      blocks.push(
        '',
        '<IfModule mod_expires.c>',
        '  ExpiresActive On',
        '  ExpiresDefault "access plus 1 month"',
        '  ExpiresByType text/html "access plus 0 seconds"',
        '  ExpiresByType text/css "access plus 1 year"',
        '  ExpiresByType application/javascript "access plus 1 year"',
        '  ExpiresByType image/jpeg "access plus 1 year"',
        '  ExpiresByType image/png "access plus 1 year"',
        '  ExpiresByType image/svg+xml "access plus 1 year"',
        '  ExpiresByType font/woff2 "access plus 1 year"',
        '</IfModule>'
      );
    }

    if (security) {
      const headers = [
        '  Header always set X-Content-Type-Options "nosniff"',
        '  Header always set X-Frame-Options "SAMEORIGIN"',
        '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
        '  Header always set Permissions-Policy "geolocation=(), microphone=(), camera=()"',
      ];
      if (https) {
        headers.push(
          '  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"'
        );
      }
      blocks.push('', '<IfModule mod_headers.c>', ...headers, '</IfModule>');
    }

    return blocks.join('\n');
  }, [caching, compression, https, security, spa, wwwMode]);

  const enabled = [
    https,
    wwwMode !== 'none',
    spa,
    caching,
    compression,
    security,
  ].filter(Boolean).length;

  return (
    <ToolLayout>
      <Panel
        description="Pick the Apache rules you need. The generated file is ready to drop into a site directory."
        title=".htaccess options"
      >
        <div className="space-y-3">
          <div className="grid gap-2 sm:grid-cols-2">
            <Toggle
              checked={https}
              hint="Redirect all HTTP requests to HTTPS."
              label="Force HTTPS"
              onChange={setHttps}
            />
            <Toggle
              checked={spa}
              hint="Serve index.html for client-side routes."
              label="SPA fallback"
              onChange={setSpa}
            />
            <Toggle
              checked={compression}
              hint="Enable mod_deflate for text, JSON and SVG."
              label="Compression"
              onChange={setCompression}
            />
            <Toggle
              checked={caching}
              hint="Long-lived cache headers for static assets."
              label="Browser caching"
              onChange={setCaching}
            />
            <Toggle
              checked={security}
              hint="nosniff, frame, referrer and permissions headers."
              label="Security headers"
              onChange={setSecurity}
            />
          </div>

          <Field
            hint={
              wwwMode === 'none' ? 'Leave the hostname untouched' : undefined
            }
            label="WWW handling"
          >
            <Select
              aria-label="WWW handling"
              onChange={(event) => setWwwMode(event.target.value as WwwMode)}
              value={wwwMode}
            >
              <option value="none">Do not change www</option>
              <option value="add">Force www.</option>
              <option value="remove">Remove www.</option>
            </Select>
          </Field>

          <div className="flex flex-wrap gap-1.5">
            <Badge variant="accent">{enabled} options enabled</Badge>
            {https && (
              <Badge variant="success">
                HSTS{security ? '' : ' (headers off)'}
              </Badge>
            )}
            {spa && <Badge>mod_rewrite</Badge>}
          </div>

          <div className="rounded-md border border-border bg-canvas-inset px-3 py-2 text-xs leading-5 text-fg-muted">
            Requires Apache 2.4 with <code>mod_rewrite</code>,{' '}
            <code>mod_headers</code>, <code>mod_deflate</code> and{' '}
            <code>mod_expires</code> as enabled above. Test with{' '}
            <code>apachectl configtest</code>.
          </div>

          {(https || wwwMode !== 'none') && (
            <div className="rounded-md border border-attention/40 bg-attention-subtle/50 px-3 py-2 text-xs leading-5 text-fg-muted">
              Redirect rules combine HTTPS and www changes into a single hop to
              avoid redirect chains. Verify the result on a staging host before
              deploying.
            </div>
          )}
        </div>
      </Panel>

      <ResultPanel
        filename=".htaccess"
        label=".htaccess"
        mime="text/plain;charset=utf-8"
        value={output}
      />
    </ToolLayout>
  );
}

const DEFAULT_SELECTED: Record<string, boolean> = {
  node: true,
  nextjs: true,
  macos: true,
  windows: true,
  ide: true,
};

export default function GitignoreGeneratorTool() {
  const [selected, setSelected] =
    useState<Record<string, boolean>>(DEFAULT_SELECTED);
  const [custom, setCustom] = useState('');

  const output = useMemo(() => {
    const seen = new Set<string>();
    const blocks: string[] = ['# Generated by CoderTools'];

    for (const preset of PRESETS) {
      if (!selected[preset.id]) {
        continue;
      }
      const lines = preset.lines.filter((line) => {
        if (seen.has(line)) {
          return false;
        }
        seen.add(line);
        return true;
      });
      if (lines.length > 0) {
        blocks.push('', `# ${preset.name}`, ...lines);
      }
    }

    const customLines = custom
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line !== '');
    const freshCustom = customLines.filter((line) => {
      if (seen.has(line)) {
        return false;
      }
      seen.add(line);
      return true;
    });
    if (freshCustom.length > 0) {
      blocks.push('', '# Custom', ...freshCustom);
    }

    return blocks.join('\n');
  }, [custom, selected]);

  const selectedCount = PRESETS.filter((preset) => selected[preset.id]).length;
  const lineCount = output
    .split('\n')
    .filter((line) => line && !line.startsWith('#')).length;

  return (
    <ToolLayout>
      <Panel
        description="Compose a .gitignore from common stacks and operating systems, then add your own patterns."
        title="Presets"
      >
        <div className="space-y-3">
          <div className="grid gap-2 sm:grid-cols-2">
            {PRESETS.map((preset) => (
              <Toggle
                checked={Boolean(selected[preset.id])}
                hint={`${preset.lines.length} patterns`}
                key={preset.id}
                label={preset.name}
                onChange={(checked) =>
                  setSelected((current) => ({
                    ...current,
                    [preset.id]: checked,
                  }))
                }
              />
            ))}
          </div>

          <div className="flex flex-wrap gap-2">
            <Button
              onClick={() =>
                setSelected(
                  Object.fromEntries(PRESETS.map((preset) => [preset.id, true]))
                )
              }
              size="sm"
            >
              Select all
            </Button>
            <Button onClick={() => setSelected({})} size="sm" variant="ghost">
              Clear all
            </Button>
            <Button
              onClick={() => setSelected(DEFAULT_SELECTED)}
              size="sm"
              variant="ghost"
            >
              Reset defaults
            </Button>
          </div>

          <Field
            hint="One pattern per line; # comments are allowed"
            label="Custom entries"
          >
            <Textarea
              aria-label="Custom gitignore entries"
              onChange={(event) => setCustom(event.target.value)}
              placeholder={'.env.local\n*.log\n!/important.log'}
              style={{ minHeight: 120 }}
              value={custom}
            />
          </Field>

          <div className="flex flex-wrap gap-1.5">
            <Badge variant="accent">
              {selectedCount} preset{selectedCount === 1 ? '' : 's'}
            </Badge>
            <Badge variant="success">
              {lineCount} pattern{lineCount === 1 ? '' : 's'}
            </Badge>
          </div>

          <div className="rounded-md border border-border bg-canvas-inset px-3 py-2 text-xs leading-5 text-fg-muted">
            Duplicate patterns are removed across presets. A line beginning with{' '}
            <code>!</code> re-includes a previously ignored path.
          </div>
        </div>
      </Panel>

      <ResultPanel
        filename=".gitignore"
        label=".gitignore"
        mime="text/plain;charset=utf-8"
        value={output}
      />
    </ToolLayout>
  );
}

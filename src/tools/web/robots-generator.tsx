'use client';

import { useMemo, useState } from 'react';

import { Badge } from '@/components/ui/Badge';
import { Callout } from '@/components/ui/Callout';
import { Field } from '@/components/ui/Field';
import { Input } from '@/components/ui/Input';
import { Panel } from '@/components/ui/Panel';
import { ResultPanel } from '@/components/ui/ResultPanel';
import { Select } from '@/components/ui/Select';
import { Textarea } from '@/components/ui/Textarea';
import { ToolLayout } from '@/components/ui/ToolLayout';

type PresetId =
  | 'allow-all'
  | 'disallow-all'
  | 'block-ai'
  | 'wordpress'
  | 'ecommerce'
  | 'custom';

const PRESETS: Record<
  Exclude<PresetId, 'custom'>,
  { agents: string; allow: string; disallow: string }
> = {
  'allow-all': { agents: '*', allow: '/', disallow: '' },
  'disallow-all': { agents: '*', allow: '', disallow: '/' },
  'block-ai': {
    agents:
      'GPTBot, ChatGPT-User, CCBot, Google-Extended, anthropic-ai, ClaudeBot, PerplexityBot',
    allow: '',
    disallow: '/',
  },
  wordpress: {
    agents: '*',
    allow: '/wp-admin/admin-ajax.php',
    disallow:
      '/wp-admin/\n/wp-login.php\n/xmlrpc.php\n/wp-content/cache/\n/?s=',
  },
  ecommerce: {
    agents: '*',
    allow: '/',
    disallow: '/cart/\n/checkout/\n/account/\n/admin/\n/search?',
  },
};

const toLines = (value: string) =>
  value
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line !== '' && !line.startsWith('#'));

const toPaths = (value: string) =>
  toLines(value).map((line) => (line.startsWith('/') ? line : `/${line}`));

export default function RobotsGeneratorTool() {
  const [preset, setPreset] = useState<PresetId>('allow-all');
  const [agents, setAgents] = useState('*');
  const [allow, setAllow] = useState('/');
  const [disallow, setDisallow] = useState('');
  const [crawlDelay, setCrawlDelay] = useState('');
  const [sitemap, setSitemap] = useState('https://example.com/sitemap.xml');

  const applyPreset = (value: PresetId) => {
    setPreset(value);
    if (value === 'custom') {
      return;
    }
    const next = PRESETS[value];
    setAgents(next.agents);
    setAllow(next.allow);
    setDisallow(next.disallow);
  };

  const agentList = agents
    .split(',')
    .map((agent) => agent.trim())
    .filter(Boolean);
  const allowList = useMemo(() => toPaths(allow), [allow]);
  const disallowList = useMemo(() => toPaths(disallow), [disallow]);

  const sitemapValue = sitemap.trim();
  let sitemapError: string | null = null;
  if (sitemapValue) {
    try {
      const url = new URL(sitemapValue);
      if (url.protocol !== 'http:' && url.protocol !== 'https:') {
        sitemapError = 'The sitemap URL must start with http:// or https://.';
      }
    } catch {
      sitemapError = 'The sitemap URL is not valid and will be omitted.';
    }
  }

  const delayValue = crawlDelay.trim();
  const delayNumber = Number(delayValue);
  const delayValid =
    delayValue === '' || (Number.isFinite(delayNumber) && delayNumber >= 0);

  const robots = useMemo(() => {
    const lines: string[] = [
      '# Generated by CoderTools',
      '# https://www.robotstxt.org/',
    ];
    const effectiveAgents = agentList.length > 0 ? agentList : ['*'];

    lines.push('');
    for (const agent of effectiveAgents) {
      lines.push(`User-agent: ${agent}`);
    }
    for (const path of allowList) {
      lines.push(`Allow: ${path}`);
    }
    for (const path of disallowList) {
      lines.push(`Disallow: ${path}`);
    }
    if (delayValid && delayValue !== '') {
      lines.push(`Crawl-delay: ${delayNumber}`);
    }
    if (sitemapValue && !sitemapError) {
      lines.push('');
      lines.push(`Sitemap: ${sitemapValue}`);
    }
    return lines.join('\n');
  }, [
    agentList,
    allowList,
    delayValue,
    delayNumber,
    delayValid,
    disallowList,
    sitemapError,
    sitemapValue,
  ]);

  return (
    <ToolLayout>
      <Panel
        description="Start from a preset or write your own groups of user-agent rules. The output follows the robots.txt specification."
        title="Rules"
      >
        <div className="space-y-3">
          <Field label="Preset">
            <Select
              onChange={(event) => applyPreset(event.target.value as PresetId)}
              value={preset}
            >
              <option value="allow-all">Allow all crawlers</option>
              <option value="disallow-all">Block all crawlers</option>
              <option value="block-ai">Block AI crawlers</option>
              <option value="wordpress">WordPress defaults</option>
              <option value="ecommerce">E-commerce (skip cart/checkout)</option>
              <option value="custom">Custom</option>
            </Select>
          </Field>

          <Field
            hint="Comma separated; use * for all crawlers"
            label="User agents"
          >
            <Input
              onChange={(event) => {
                setPreset('custom');
                setAgents(event.target.value);
              }}
              placeholder="* or Googlebot, Bingbot"
              spellCheck={false}
              value={agents}
            />
          </Field>

          <div className="grid gap-3 sm:grid-cols-2">
            <Field hint="One path per line" label="Allow">
              <Textarea
                aria-label="Allowed paths"
                onChange={(event) => {
                  setPreset('custom');
                  setAllow(event.target.value);
                }}
                placeholder="/"
                style={{ minHeight: 96 }}
                value={allow}
              />
            </Field>
            <Field hint="One path per line" label="Disallow">
              <Textarea
                aria-label="Disallowed paths"
                onChange={(event) => {
                  setPreset('custom');
                  setDisallow(event.target.value);
                }}
                placeholder="/admin/"
                style={{ minHeight: 96 }}
                value={disallow}
              />
            </Field>
          </div>

          <div className="grid gap-2.5 sm:grid-cols-2">
            <Field label="Crawl delay (seconds)">
              <Input
                min={0}
                onChange={(event) => setCrawlDelay(event.target.value)}
                placeholder="Optional"
                type="number"
                value={crawlDelay}
              />
            </Field>
            <Field label="Sitemap URL">
              <Input
                onChange={(event) => setSitemap(event.target.value)}
                placeholder="https://example.com/sitemap.xml"
                spellCheck={false}
                value={sitemap}
              />
            </Field>
          </div>

          {!delayValid && (
            <Callout variant="error">
              Crawl delay must be zero or a positive number.
            </Callout>
          )}
          {sitemapError && <Callout variant="warning">{sitemapError}</Callout>}

          <div className="flex flex-wrap gap-1.5">
            <Badge variant="accent">
              {agentList.length || 1} agent
              {(agentList.length || 1) === 1 ? '' : 's'}
            </Badge>
            <Badge variant="success">{allowList.length} allow</Badge>
            <Badge variant="warning">{disallowList.length} disallow</Badge>
          </div>

          <p className="text-[11px] leading-5 text-fg-muted">
            Crawlers generally honor the most specific matching rule. robots.txt
            is advisory; it does not protect private data.
          </p>
        </div>
      </Panel>

      <ResultPanel
        filename="robots.txt"
        label="robots.txt"
        mime="text/plain;charset=utf-8"
        value={robots}
      />
    </ToolLayout>
  );
}
